def load_canonical_objects(root: Path) -> dict[str, Any]:
    """Load the canonical PIPD objects from `root`: registry + schema files, the
    profile trio, and the S5-S8 seam fixtures. Pure reads."""
    root = Path(root)
    objects: dict[str, SourceRef] = {}
    raw: dict[str, Any] = {}
    order: list[str] = []

    def add(ref: SourceRef, payload: Any) -> None:
        objects[ref.object_id] = ref
        raw[ref.object_id] = payload
        order.append(ref.object_id)

    reg_path = root / "schemas" / "registry.json"
    registry = json.loads(reg_path.read_text(encoding="utf-8"))
    add(_ref("REGISTRY:CONTRACT-FAMILIES", registry.get("schema", "PIPD-S0-CONTRACT-REGISTRY/1"),
             "1", "schemas/registry.json", sha256_file(reg_path)), registry)

    families = []
    for fam in registry.get("families", []):
        rel = fam["schema_file"]
        spath = root / rel
        schema = json.loads(spath.read_text(encoding="utf-8"))
        sid = schema.get("$id", "")
        version = sid.rsplit(":", 1)[-1] if sid else "0"
        add(_ref(f"S0:{fam['contract']}", sid, version, rel, sha256_file(spath)),
            {"family": fam, "schema": schema})
        families.append(fam["contract"])

    prof_path = root / "src" / "pipd_ls_sp" / "profiles.py"
    prof_text = prof_path.read_text(encoding="utf-8")
    vals: dict[str, Any] = {}
    for node in ast.parse(prof_text).body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in ("PROFILES", "AXES"):
                    vals[target.id] = ast.literal_eval(node.value)
    if "PROFILES" not in vals or "AXES" not in vals:
        raise MissingField("profiles.py must define PROFILES and AXES")
    add(_ref("PROFILE:TRIO", "PIPD-PROFILE-TRIO/1", "1", "src/pipd_ls_sp/profiles.py",
             sha256_file(prof_path)), vals)

    seams = {}
    for stage in ("s5", "s6", "s7", "s8"):
        rel = f"fixtures/s5_s8/{stage}_compat.json"
        spath = root / rel
        fixture = json.loads(spath.read_text(encoding="utf-8"))
        seams[stage.upper()] = fixture
        add(_ref(f"SEAM:{stage.upper()}", "PIPD-SEAM-COMPAT/1", "1", rel, sha256_file(spath)),
            fixture)

    adapter_ref = _ref("ADAPTER:MAPPING", "PIPD-ADAPTER-MAPPING/1", "1",
                       "src/pipd_ls_sp/projection.py#ADAPTER_MAPPING",
                       sha256_text(canonical_json(ADAPTER_MAPPING)))
    add(adapter_ref, ADAPTER_MAPPING)

    return {"objects": objects, "raw": raw, "order": order, "registry": registry,
            "profiles": vals, "seams": seams, "root": root}


def _aggregate_hash(refs: list[SourceRef] | tuple[SourceRef, ...]) -> str:
    return sha256_text(canonical_json([r.to_json() for r in refs]))


