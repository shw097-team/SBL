def compile_projection_ir(root: Path) -> dict[str, Any]:
    """Compile the typed projection IR from canonical objects + profile + adapter mapping."""
    canon = load_canonical_objects(root)
    artifacts: list[dict] = []

    def source_refs(oids: list[str]) -> list[SourceRef]:
        return [canon["objects"][oid] for oid in oids]

    for doc_id, spec in WEB_DOC_SPECS.items():
        refs = source_refs(_resolve_doc_sources(canon, doc_id))
        payload = _doc_payload(canon, doc_id)
        payload["doc_id"] = doc_id
        payload["title"] = spec["title"]
        art = ArtifactIR(
            artifact_id=f"web:{doc_id}",
            kind=WEB_DOC_KIND,
            path=spec["file"],
            denominator=True,
            source_objects=tuple(refs),
            source_hash=_aggregate_hash(refs),
            capability_loss=tuple(CapabilityLossRecord(**r) for r in WEB_CAPABILITY_LOSS),
            nack=tuple(NackRecord(**r) for r in WEB_NACK),
            scope=ALLOWED_SCOPE,
            payload=payload,
        )
        artifacts.append(art.to_json())

    for surface, host_spec in ADAPTER_MAPPING["hosts"].items():
        record = _host_record(canon, surface)
        refs = source_refs(host_spec["source_objects"])
        art = ArtifactIR(
            artifact_id=f"host:{surface}",
            kind=HOST_KIND,
            path=f"{host_spec['dir']}/{host_spec['entry_file']}",
            denominator=False,
            source_objects=tuple(refs),
            source_hash=_aggregate_hash(refs),
            capability_loss=tuple(CapabilityLossRecord(**r) for r in host_spec["capability_loss"]),
            nack=tuple(NackRecord(**r) for r in host_spec["nack"]),
            scope=ALLOWED_SCOPE,
            payload=record,
        )
        artifacts.append(art.to_json())

    ui_refs = [canon["objects"]["ADAPTER:MAPPING"]]
    ui_payload = {"category": UI_KIND, "excluded_from_web_denominator": True,
                  "files": list(UI_FILES), "web_denominator": WEB_DOC_FILES}
    art = ArtifactIR(
        artifact_id="ui:OPTIONAL_SITE_UI",
        kind=UI_KIND,
        path=f"{UI_DIR}/",
        denominator=False,
        source_objects=tuple(ui_refs),
        source_hash=_aggregate_hash(ui_refs),
        capability_loss=(CapabilityLossRecord(
            record_type="CapabilityLoss", loss_id="LOSS-UI-01",
            capability="semantic document status",
            reason="site UI five files are OPTIONAL_SITE_UI and carry no PIPD semantic contract",
            severity="DECLARED"),),
        nack=(NackRecord(
            record_type="NACK", nack_id="NACK-UI-01",
            statement="OPTIONAL_SITE_UI files are excluded from the Web denominator and cannot pass G-S3-WEB",
            basis="R-AUD-003"),),
        scope=ALLOWED_SCOPE,
        payload=ui_payload,
    )
    artifacts.append(art.to_json())

    ir = {
        "schema": SCHEMA_IR,
        "schema_version": SCHEMA_VERSION,
        "profile": {"profiles": canon["profiles"]["PROFILES"], "axes": list(canon["profiles"]["AXES"]),
                    "routing": ADAPTER_MAPPING["routing"]},
        "adapter_mapping": ADAPTER_MAPPING,
        "source_index": [canon["objects"][oid].to_json() for oid in canon["order"]],
        "artifacts": artifacts,
    }
    ir["projection_parity_sha256"] = _parity_hash(ir)
    return ir


def _parity_hash(ir: dict) -> str:
    rows = sorted([[a["artifact_id"], a["path"], a["source_hash"],
                    sha256_text(canonical_json(a["payload"]))] for a in ir["artifacts"]])
    return sha256_text(canonical_json(rows))


# ---------------------------------------------------------------- IR validation

def validate_projection_ir(ir: dict) -> dict:
    """Refuse empty payloads, missing fields and scope widening (R-AUD-015 negatives)."""
    if not isinstance(ir, dict):
        raise MissingField("projection IR must be an object")
    for key in IR_FIELDS:
        if key not in ir:
            raise MissingField(f"projection IR missing {key}")
    if ir["schema"] != SCHEMA_IR:
        raise MissingField(f"projection IR schema {ir['schema']!r} != {SCHEMA_IR}")
    artifacts = ir["artifacts"]
    if not isinstance(artifacts, list) or not artifacts:
        raise EmptyPayload("projection IR carries no artifacts")
    for art in artifacts:
        for key in ARTIFACT_FIELDS:
            if key not in art:
                raise MissingField(f"artifact {art.get('artifact_id', '?')} missing {key}")
        if art["kind"] not in (WEB_DOC_KIND, HOST_KIND, UI_KIND):
            raise UnsupportedSurface(f"artifact {art['artifact_id']} has unknown kind {art['kind']!r}")
        if not isinstance(art["payload"], (dict, list, str)) or not art["payload"]:
            raise EmptyPayload(f"artifact {art['artifact_id']} has an empty payload")
        for scope_entry in art["scope"]:
            if scope_entry not in ALLOWED_SCOPE:
                raise ScopeWidening(
                    f"artifact {art['artifact_id']} widens scope to {scope_entry!r}")
        refs = art["source_objects"]
        if not isinstance(refs, list) or not refs:
            raise MissingField(f"artifact {art['artifact_id']} has no source objects")
        for ref in refs:
            for key in SOURCE_REF_FIELDS:
                if key not in ref or not ref[key]:
                    raise MissingField(
                        f"artifact {art['artifact_id']} source ref missing {key}")
        computed = _aggregate_hash([SourceRef(**r) for r in refs])
        if art["source_hash"] != computed:
            raise StaleSource(f"artifact {art['artifact_id']} source hash does not match sources")
        for rec, fields, kind_name in ((art["capability_loss"], LOSS_FIELDS, "CapabilityLoss"),
                                       (art["nack"], NACK_FIELDS, "NACK")):
            if not isinstance(rec, list) or not rec:
                raise EmptyPayload(f"artifact {art['artifact_id']} has no {kind_name} record")
            for item in rec:
                for key in fields:
                    if key not in item or item[key] in (None, ""):
                        raise MissingField(
                            f"artifact {art['artifact_id']} {kind_name} record missing {key}")
        if art["kind"] == HOST_KIND:
            record = art["payload"]
            if not isinstance(record, dict):
                raise MissingField(f"host artifact {art['artifact_id']} payload is not a record")
            if not record.get("source_refs"):
                raise MarkerOnlyStub(f"host artifact {art['artifact_id']} is a marker-only stub")
            if not record.get("field_contract"):
                raise MarkerOnlyStub(f"host artifact {art['artifact_id']} has no field contract")
    return ir


# ---------------------------------------------------------------- renderers

def _table(columns: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(columns) + " |",
             "| " + " | ".join("---" for _ in columns) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(lines)


def _meta_block(meta: dict) -> str:
    return ("<!--PIPD-DOC-META\n"
            + json.dumps(meta, ensure_ascii=False, indent=1, sort_keys=True)
            + "\n-->")


def _doc_meta(art: dict) -> dict:
    return {
        "schema": SCHEMA_DOC_META,
        "schema_version": SCHEMA_VERSION,
        "doc_id": art["payload"]["doc_id"],
        "kind": art["kind"],
        "denominator": art["denominator"],
        "source_objects": art["source_objects"],
        "source_hash": art["source_hash"],
        "capability_loss": art["capability_loss"],
        "nack": art["nack"],
        "scope": list(art["scope"]),
    }


def render_web_doc(art: dict) -> str:
    payload = art["payload"]
    out = [f"# {payload['title']}", "", _meta_block(_doc_meta(art)), ""]
    out += ["## Source Objects", "",
            _table(["object_id", "schema", "schema_version", "source_path", "source_hash"],
                   [[r["object_id"], r["schema"], r["schema_version"], r["source_path"],
                     r["source_hash"]] for r in art["source_objects"]]), ""]
    out += ["## Capability Loss", "",
            _table(["loss_id", "record_type", "capability", "reason", "severity"],
                   [[r["loss_id"], r["record_type"], r["capability"], r["reason"], r["severity"]]
                    for r in art["capability_loss"]]), ""]
    out += ["## NACK", "",
            _table(["nack_id", "record_type", "statement", "basis"],
                   [[r["nack_id"], r["record_type"], r["statement"], r["basis"]]
                    for r in art["nack"]]), ""]
    for section in payload["sections"]:
        out += [f"## {section['heading']}", "",
                _table(section["columns"], section["rows"]), ""]
    return "\n".join(out)


def _record_block(record: dict) -> str:
    return ("<!--PIPD-HOST-RECORD\n"
            + json.dumps(record, ensure_ascii=False, indent=1, sort_keys=True)
            + "\n-->")


def render_host_entry(record: dict) -> str:
    if record["entry_kind"] == "skill_projection":
        skill = record["payload"]
        out = ["---", f"name: {skill['skill_id']}",
               "description: Project canonical PIPD objects, profiles and the adapter mapping "
               "onto Web and host surfaces with declared capability loss. Fixture/mock contract "
               "only; S5/S6 NOT_AUTHORISED.", "---", "",
               f"# {skill['skill_id']}", "", _record_block(record), "",
               "## Contract", "",
               _table(["field", "type", "required", "source_object_id"],
                      [[r["name"], r["type"], "true" if r["required"] else "false",
                        r["source_object_id"]] for r in record["field_contract"]]), "",
               _table(["role", "object_id"],
                      [["input", skill["input_object_id"]], ["output", skill["output_object_id"]]]
                      + [["contract_ref", oid] for oid in skill["contract_refs"]]), "",
               "## Trigger", ""]
        out += [f"- {line}" for line in skill["trigger"]]
        out += ["", "## Non-Trigger", ""]
        out += [f"- {line}" for line in skill["non_trigger"]]
        out += ["", "## Capability Loss", "",
                _table(["loss_id", "capability", "reason", "severity"],
                       [[r["loss_id"], r["capability"], r["reason"], r["severity"]]
                        for r in record["capability_loss"]]), "",
                "## NACK", "",
                _table(["nack_id", "statement", "basis"],
                       [[r["nack_id"], r["statement"], r["basis"]]
                        for r in record["nack"]]), ""]
        return "\n".join(out)
    return json.dumps(record, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def render_ui_file(name: str) -> str:
    marker = ("OPTIONAL_SITE_UI: excluded from the Web denominator (R-AUD-003). "
              "The Web pack is the five PIPD_*.md documents.")
    if name == "index.html":
        return ("<!doctype html><meta charset=utf-8><title>PIPD-LS-SP OPTIONAL_SITE_UI</title>\n"
                f"<!-- {marker} -->\n<div id=app></div><script src=app.js></script>\n")
    if name == "app.js":
        return ("// " + marker + "\n"
                "fetch('PROJECTION_IR.json').then(r => r.json()).then(ir => {"
                "document.getElementById('app').textContent = "
                "'PIPD-LS-SP OPTIONAL_SITE_UI ' + ir.projection_parity_sha256;});\n")
    if name == "styles.css":
        return "/* " + marker + " */\nbody{font-family:system-ui;margin:2rem}\n"
    if name == "manifest.webmanifest":
        return json.dumps({"name": "PIPD-LS-SP OPTIONAL_SITE_UI", "short_name": "PIPD-UI",
                           "version": "0.1.0", "category": UI_KIND,
                           "excluded_from_web_denominator": True},
                          ensure_ascii=False, indent=1, sort_keys=True) + "\n"
    if name == "README.md":
        return ("# OPTIONAL_SITE_UI\n\n" + marker + "\n\n"
                "These five files are a site UI pack: `index.html`, `app.js`, `styles.css`, "
                "`manifest.webmanifest`, `README.md`. They are NOT the PIPD Web documents and "
                "are never counted in the Web denominator.\n")
    raise MissingField(f"unknown UI file {name!r}")


