def _schema_props(entry: dict) -> tuple[list[dict], list[str]]:
    """Field contract rows derived from a canonical schema object."""
    schema = entry["schema"]
    required = list(schema.get("required", []))
    rows = []
    for name in schema.get("properties", {}):
        spec = schema.get("properties", {}).get(name) or {}
        dtype = spec.get("type", "object") if isinstance(spec, dict) else "object"
        if dtype not in TYPE_VOCAB:
            dtype = "object"
        rows.append({"name": name, "type": dtype, "required": name in required})
    return rows, required


def _derive_field_contract(canon: dict, host_spec: dict) -> list[dict]:
    rows: list[dict] = []
    seen: dict[str, int] = {}
    for oid in host_spec["field_contract_sources"]:
        entry = canon["raw"].get(oid)
        if not isinstance(entry, dict) or "schema" not in entry:
            raise MissingField(f"field contract source {oid} is not a canonical schema object")
        prop_rows, _ = _schema_props(entry)
        for row in prop_rows:
            row = dict(row)
            row["source_object_id"] = oid
            if row["name"] in seen:
                prev = rows[seen[row["name"]]]
                prev["required"] = prev["required"] or row["required"]
            else:
                seen[row["name"]] = len(rows)
                rows.append(row)
    return rows


def _compatibility(canon: dict, host_spec: dict) -> dict:
    source = host_spec.get("compatibility_source")
    if source and source in canon["raw"]:
        fixture = canon["raw"][source]
        return {"mode": "FIXTURE_MOCK",
                "fixture_kind": fixture.get("fixture_kind", "compatibility"),
                "live_status": fixture.get("live_status", "NOT_RUN"),
                "seam_schemas": list(fixture.get("seam_schemas", [])),
                "seam_source": source,
                "asserted": dict(fixture.get("asserted", {}))}
    return {"mode": "FIXTURE_MOCK", "fixture_kind": "compatibility",
            "live_status": "NOT_RUN",
            "seam_schemas": ["SurfaceProjectionManifest", "ProfileBinding"],
            "seam_source": "ADAPTER:MAPPING",
            "asserted": {"itch_contract_only": True, "no_live_receiver_ack": True,
                         "no_world_effect": True}}


def _host_record(canon: dict, surface: str) -> dict:
    host_spec = ADAPTER_MAPPING["hosts"][surface]
    refs = [canon["objects"][oid].to_json() for oid in host_spec["source_objects"]]
    field_contract = _derive_field_contract(canon, host_spec)
    payload = _host_payload(canon, surface, host_spec)
    record = {
        "schema": SCHEMA_HOST_RECORD,
        "schema_version": SCHEMA_VERSION,
        "surface": surface,
        "entry_kind": host_spec["entry_kind"],
        "contract_version": SCHEMA_VERSION,
        "field_contract": field_contract,
        "source_refs": refs,
        "compatibility": _compatibility(canon, host_spec),
        "capability_loss": [dict(r) for r in host_spec["capability_loss"]],
        "nack": [dict(r) for r in host_spec["nack"]],
        "provider": dict(host_spec["provider"]),
        "permissions": list(host_spec["allowed_permissions"]),
        "scope": list(ALLOWED_SCOPE),
        "payload": payload,
    }
    return record


def _host_payload(canon: dict, surface: str, host_spec: dict) -> dict:
    if host_spec["entry_kind"] == "skill_projection":
        return {
            "skill_id": host_spec["skill_id"],
            "input_object_id": "S0:SurfaceProjectionManifest",
            "output_object_id": "S0:ProfileBinding",
            "contract_refs": list(host_spec["source_objects"]),
            "trigger": [
                "user asks to project canonical PIPD objects onto Web or host surfaces",
                "a surface pack or host projection must be (re)generated from canonical sources",
            ],
            "non_trigger": [
                "live HGK execution or GENIE integration requests (S5/S6 NOT_AUTHORISED)",
                "requirement compilation or pipeline entry points (owned by another lane)",
            ],
        }
    if host_spec["entry_kind"] == "receiver_map":
        receivers = []
        for oid in host_spec["required_mappings"]:
            entry = canon["raw"][oid]
            rows, _ = _schema_props(entry)
            receivers.append({
                "receiver_id": "hgk." + oid.split(":", 1)[1].lower().replace("-", "."),
                "source_object_id": oid,
                "entry": "receive_" + oid.split(":", 1)[1].lower().replace("-", "_"),
                "ack_state": "NACK_ONLY",
                "fields": [{"name": r["name"], "type": r["type"], "required": r["required"]}
                           for r in rows],
            })
        return {"abi_version": "PIPD-HGK-RECEIVER-ABI/1", "receivers": receivers}
    if host_spec["entry_kind"] == "object_crosswalk":
        targets = _required_targets(canon, host_spec)
        target_sources = {
            "ProductGraph": "S0:PD-PKG",
            "Profile": "S0:ProfileBinding",
            "Bundle": "S0:PI-PKG",
            "GENIEArtifact": "S0:ArtifactIdentity",
        }
        mappings = []
        for target in targets:
            oid = target_sources[target]
            ref = canon["objects"][oid]
            mappings.append({
                "source_object_id": oid,
                "source_schema": ref.schema,
                "source_version": ref.schema_version,
                "target": target,
                "target_ref": f"urn:genie:seam:{target}",
                "direction": "REFERENCE_ONLY",
            })
        return {"crosswalk_version": "PIPD-GENIE-CROSSWALK/1",
                "required_targets": targets, "mappings": mappings}
    raise UnsupportedSurface(f"unknown entry kind {host_spec['entry_kind']!r}")


def _required_targets(canon: dict, host_spec: dict) -> list[str]:
    oid = host_spec.get("required_targets_from")
    if not oid:
        return []
    entry = canon["raw"].get(oid)
    if not isinstance(entry, dict):
        raise MissingField(f"required target source {oid} missing")
    schema = entry["schema"]
    targets = list(schema.get("properties", {}).get("target_refs", {}).get("required", []))
    if not targets:
        raise MissingField(f"{oid} declares no required target_refs")
    return targets


def _resolve_doc_sources(canon: dict, spec_key: str) -> list[str]:
    spec = WEB_DOC_SPECS[spec_key]["source_objects"]
    if spec == "ALL":
        return list(canon["order"])
    out = []
    for oid in spec:
        if oid == "S0:*":
            out.extend(o for o in canon["order"] if o.startswith("S0:"))
        else:
            out.append(oid)
    return out


