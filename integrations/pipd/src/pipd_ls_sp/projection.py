_META_RE = re.compile(r"<!--PIPD-DOC-META\s*\n(.*?)\n-->", re.S)
_RECORD_RE = re.compile(r"<!--PIPD-HOST-RECORD\s*\n(.*?)\n-->", re.S)
_FRONTMATTER_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)


def _fail(code_exc: type[ProjectionError], reason: str, path: str) -> dict:
    return {"code": code_exc.code, "mutation": code_exc.mutation,
            "reason": reason, "path": path}


def _check_record_common(record: dict, expected: dict, path: str, failures: list) -> None:
    """Field-level contract / source refs / compatibility / loss / provider / permission /
    scope checks shared by every host loader. `record` is what is on disk."""
    for key in HOST_RECORD_FIELDS:
        if key not in record:
            failures.append(_fail(MissingField, f"host record missing {key}", path))
            return
    surface = record["surface"]
    if surface not in ADAPTER_MAPPING["hosts"]:
        failures.append(_fail(UnsupportedHost, f"unsupported host surface {surface!r}", path))
        return
    if record["entry_kind"] != ADAPTER_MAPPING["hosts"][surface]["entry_kind"]:
        failures.append(_fail(MissingField,
                              f"entry kind {record['entry_kind']!r} does not match adapter mapping",
                              path))
    expected_contract = expected["field_contract"]
    if not record["field_contract"]:
        failures.append(_fail(MarkerOnlyStub, "field-level contract is empty", path))
    elif record["field_contract"] != expected_contract:
        missing = [r["name"] for r in expected_contract
                   if r not in record["field_contract"]]
        failures.append(_fail(MissingField,
                              f"field contract does not match derived contract; missing {missing}",
                              path))
    if not record["source_refs"]:
        failures.append(_fail(MarkerOnlyStub, "no source references", path))
    known = set(load_canonical_objects_cache["objects"])
    for ref in record["source_refs"]:
        for key in SOURCE_REF_FIELDS:
            if key not in ref or not ref[key]:
                failures.append(_fail(MissingField, f"source ref missing {key}", path))
                break
        else:
            if ref["object_id"] not in known:
                failures.append(_fail(UnknownSourceObject,
                                      f"unknown source object {ref['object_id']!r}", path))
            elif ref["source_hash"] != load_canonical_objects_cache["objects"][ref["object_id"]].source_hash:
                failures.append(_fail(StaleSource,
                                      f"stale source hash for {ref['object_id']}", path))
    compat = record["compatibility"]
    if not isinstance(compat, dict) or "mode" not in compat or "live_status" not in compat:
        failures.append(_fail(MissingField, "compatibility record missing", path))
    else:
        if compat.get("live_status") != "NOT_RUN":
            failures.append(_fail(ProviderOff,
                                  f"live_status {compat.get('live_status')!r} claims a live run "
                                  "while the provider is off", path))
        if compat.get("mode") != "FIXTURE_MOCK":
            failures.append(_fail(ProviderOff,
                                  f"compatibility mode {compat.get('mode')!r} claims more than "
                                  "fixture/mock", path))
    for recs, fields, name in ((record["capability_loss"], LOSS_FIELDS, "CapabilityLoss"),
                               (record["nack"], NACK_FIELDS, "NACK")):
        if not isinstance(recs, list) or not recs:
            failures.append(_fail(EmptyPayload, f"no {name} record carried", path))
            continue
        for item in recs:
            for key in fields:
                if key not in item or item[key] in (None, ""):
                    failures.append(_fail(MissingField, f"{name} record missing {key}", path))
                    break
    host_spec = ADAPTER_MAPPING["hosts"][surface]
    declared_losses = {r["loss_id"] for r in host_spec["capability_loss"]}
    carried_losses = {r.get("loss_id") for r in record["capability_loss"] or []}
    if not declared_losses <= carried_losses:
        failures.append(_fail(MissingField,
                              f"capability-loss record missing {sorted(declared_losses - carried_losses)}",
                              path))
    provider = record["provider"]
    expected_provider = host_spec["provider"]
    if not isinstance(provider, dict):
        failures.append(_fail(MissingField, "provider record missing", path))
    else:
        if provider.get("live_integration") is not False:
            failures.append(_fail(ProviderOff,
                                  "provider claimed live integration while it is off "
                                  f"({expected_provider['provider_id']} {expected_provider['admission_state']})",
                                  path))
        if provider.get("admission_state") != expected_provider["admission_state"]:
            failures.append(_fail(ProviderOff,
                                  f"provider admission state {provider.get('admission_state')!r} "
                                  f"diverges from authoritative {expected_provider['admission_state']!r}",
                                  path))
    allowed = set(host_spec["allowed_permissions"])
    for perm in record["permissions"]:
        if perm not in allowed:
            failures.append(_fail(PermissionWidening,
                                  f"permission {perm!r} is outside the host contract {sorted(allowed)}",
                                  path))
    for scope_entry in record["scope"]:
        if scope_entry not in ALLOWED_SCOPE:
            failures.append(_fail(ScopeWidening,
                                  f"scope {scope_entry!r} widens beyond {list(ALLOWED_SCOPE)}", path))


def _check_required_mappings(record: dict, surface: str, path: str, failures: list) -> None:
    host_spec = ADAPTER_MAPPING["hosts"][surface]
    required = set(host_spec["required_mappings"])
    kind = record["entry_kind"]
    payload = record.get("payload") or {}
    if kind == "skill_projection":
        carried = set(payload.get("contract_refs", []))
    elif kind == "receiver_map":
        carried = {r.get("source_object_id") for r in payload.get("receivers", [])}
    else:
        carried = {m.get("source_object_id") for m in payload.get("mappings", [])}
    missing = sorted(required - carried)
    if missing:
        failures.append(_fail(MissingRequiredMapping,
                              f"missing required mapping for {missing}", path))


def _load_skill_projection(record: dict, path: str, failures: list) -> dict:
    skill = record.get("payload") or {}
    for key in ("skill_id", "trigger", "non_trigger", "contract_refs",
                "input_object_id", "output_object_id"):
        if key not in skill or skill[key] in (None, "", []):
            failures.append(_fail(MissingField, f"skill payload missing {key}", path))
    if skill.get("skill_id") != ADAPTER_MAPPING["hosts"]["host:generic-skills"]["skill_id"]:
        failures.append(_fail(MissingField, "skill_id does not match the adapter mapping", path))
    return {"loader": "skill_projection_v1", "skill_id": skill.get("skill_id"),
            "contract_refs": skill.get("contract_refs", [])}


def _load_receiver_map(record: dict, path: str, failures: list) -> dict:
    payload = record.get("payload") or {}
    receivers = payload.get("receivers")
    if not isinstance(receivers, list) or not receivers:
        failures.append(_fail(EmptyPayload, "receiver map carries no receivers", path))
        return {"loader": "receiver_map_v1", "receivers": 0}
    seen = set()
    typed = 0
    for receiver in receivers:
        for key in ("receiver_id", "source_object_id", "entry", "ack_state", "fields"):
            if key not in receiver:
                failures.append(_fail(MissingField, f"receiver missing {key}", path))
                break
        else:
            if receiver["receiver_id"] in seen:
                failures.append(_fail(MissingField,
                                      f"duplicate receiver id {receiver['receiver_id']}", path))
            seen.add(receiver["receiver_id"])
            if not receiver["fields"]:
                failures.append(_fail(EmptyPayload,
                                      f"receiver {receiver['receiver_id']} has no typed fields", path))
            for field_row in receiver["fields"]:
                for key in ("name", "type", "required"):
                    if key not in field_row:
                        failures.append(_fail(MissingField,
                                              f"receiver field missing {key}", path))
                        break
                else:
                    if field_row["type"] not in TYPE_VOCAB:
                        failures.append(_fail(MissingField,
                                              f"receiver field type {field_row['type']!r} "
                                              "is not in the type vocabulary", path))
                    typed += 1
    return {"loader": "receiver_map_v1", "receivers": len(receivers), "typed_fields": typed}


def _load_object_crosswalk(record: dict, path: str, failures: list) -> dict:
    payload = record.get("payload") or {}
    mappings = payload.get("mappings")
    if not isinstance(mappings, list) or not mappings:
        failures.append(_fail(EmptyPayload, "object crosswalk carries no mappings", path))
        return {"loader": "object_crosswalk_v1", "mappings": 0}
    targets_required = set(_required_targets(load_canonical_objects_cache,
                                             ADAPTER_MAPPING["hosts"]["host:genie-adapter"]))
    carried_targets = set()
    for mapping in mappings:
        for key in ("source_object_id", "source_schema", "source_version", "target",
                    "target_ref", "direction"):
            if key not in mapping or mapping[key] in (None, ""):
                failures.append(_fail(MissingField, f"mapping missing {key}", path))
                break
        else:
            if mapping["direction"] != "REFERENCE_ONLY":
                failures.append(_fail(ScopeWidening,
                                      f"mapping direction {mapping['direction']!r} is not "
                                      "reference-only (no truth writeback)", path))
            if mapping["target"] in targets_required:
                carried_targets.add(mapping["target"])
    missing = sorted(targets_required - carried_targets)
    if missing:
        failures.append(_fail(MissingRequiredMapping,
                              f"missing required target mapping {missing}", path))
    return {"loader": "object_crosswalk_v1", "mappings": len(mappings),
            "targets": sorted(carried_targets)}


_LOADERS = {
    "skill_projection": _load_skill_projection,
    "receiver_map": _load_receiver_map,
    "object_crosswalk": _load_object_crosswalk,
}


# module-level cache set by check functions (pure reads of the given root)
load_canonical_objects_cache: dict[str, Any] = {}


def _check_host_dir(out: Path, surface: str, expected_art: dict, failures: list) -> dict:
    host_spec = ADAPTER_MAPPING["hosts"][surface]
    d = out / host_spec["dir"]
    path = f"{host_spec['dir']}/{host_spec['entry_file']}"
    row = {"host": surface, "path": path, "loader": host_spec["loader"],
           "effective_load": False, "resolved": None}
    if not d.is_dir():
        failures.append(_fail(MissingRequiredHost, f"host projection dir {host_spec['dir']} absent",
                              host_spec["dir"]))
        return row
    entry = d / host_spec["entry_file"]
    if not entry.is_file():
        failures.append(_fail(HostEntryMissing, f"host entry {host_spec['entry_file']} absent", path))
        return row
    text = entry.read_text(encoding="utf-8")
    if not text.strip():
        failures.append(_fail(EmptyPayload, "host entry is empty", path))
        return row

    record = None
    if host_spec["entry_kind"] == "skill_projection":
        fm = _FRONTMATTER_RE.match(text)
        block = _RECORD_RE.search(text)
        if not fm or not block:
            failures.append(_fail(MarkerOnlyStub,
                                  "skill projection has no loadable frontmatter/record "
                                  "(marker-only stub cannot be effective-loaded)", path))
            return row
        front = {}
        for line in fm.group(1).splitlines():
            if ": " in line:
                k, v = line.split(": ", 1)
                front[k.strip()] = v.strip()
        if "name" not in front or "description" not in front:
            failures.append(_fail(MissingField, "skill frontmatter missing name/description", path))
        try:
            record = json.loads(block.group(1))
        except json.JSONDecodeError as exc:
            failures.append(_fail(InvalidEntry, f"host record block is not JSON: {exc}", path))
            return row
    else:
        try:
            record = json.loads(text)
        except json.JSONDecodeError as exc:
            failures.append(_fail(InvalidEntry, f"host entry is not JSON: {exc}", path))
            return row

    if not isinstance(record, dict) or not record.get("source_refs") or not record.get("field_contract"):
        failures.append(_fail(MarkerOnlyStub,
                              "host entry is a marker-only stub: no field contract / source "
                              "references, so effective load cannot be satisfied", path))
        return row

    _check_record_common(record, expected_art["payload"], path, failures)
    _check_required_mappings(record, surface, path, failures)
    resolved = _LOADERS[host_spec["entry_kind"]](record, path, failures)
    if record != expected_art["payload"]:
        failures.append(_fail(NotDerived,
                              "host entry is not the derivation of the canonical sources "
                              "(free-text or tampered projection)", path))
    row["source_ref_hashes"] = {r.get("object_id", f"ref-{i}"): r.get("source_hash", "")
                                for i, r in enumerate(record.get("source_refs") or [])
                                if isinstance(r, dict)}
    row["resolved"] = resolved
    row["effective_load"] = not any(f["path"] == path for f in failures)
    return row


def check_host_surfaces(root: Path, out: Path) -> dict[str, Any]:
    """G-S3-HOST semantic gate: three hosts, real effective loads, typed refusals."""
    global load_canonical_objects_cache
    out = Path(out)
    load_canonical_objects_cache = load_canonical_objects(root)
    ir = compile_projection_ir(root)
    failures: list[dict] = []
    rows: list[dict] = []

    expected_dirs = {spec["dir"] for spec in ADAPTER_MAPPING["hosts"].values()}
    present_dirs = {p.name for p in out.iterdir() if p.is_dir() and p.name.startswith("host_")} \
        if out.is_dir() else set()
    for extra in sorted(present_dirs - expected_dirs):
        failures.append(_fail(UnsupportedHost, f"unsupported host projection {extra!r}", extra))
    for missing in sorted(expected_dirs - present_dirs):
        failures.append(_fail(MissingRequiredHost, f"required host projection {missing!r} absent",
                              missing))

    artifacts_by_path = {a["path"]: a for a in ir["artifacts"]}
    for surface, host_spec in ADAPTER_MAPPING["hosts"].items():
        expected_art = artifacts_by_path[f"{host_spec['dir']}/{host_spec['entry_file']}"]
        rows.append(_check_host_dir(out, surface, expected_art, failures))

    # semantic parity: every host binds to the same live canonical truth
    parity = "PASS"
    seen: dict[str, str] = {}
    for row in rows:
        for object_id, digest in (row.get("source_ref_hashes") or {}).items():
            if seen.setdefault(object_id, digest) != digest:
                parity = "FAIL"
                failures.append(_fail(ParityMismatch,
                                      f"source object {object_id} diverges between host projections",
                                      row["path"]))

    verdict = "PASS" if not failures else "FAIL"
    return {
        "schema": "PIPD-HOST-PROJECTIONS-CHECK/1",
        "surface": "host",
        "verdict": verdict,
        "host_count": f"{sum(1 for r in rows if r['effective_load'])}/{len(ADAPTER_MAPPING['hosts'])}",
        "required_hosts": sorted(ADAPTER_MAPPING["hosts"]),
        "rows": rows,
        "semantic_parity": parity if not failures else "FAIL",
        "capability_loss": {surface: [r["loss_id"] for r in spec["capability_loss"]]
                            for surface, spec in ADAPTER_MAPPING["hosts"].items()},
        "compatibility": {surface: _compatibility(load_canonical_objects_cache, spec)
                          for surface, spec in ADAPTER_MAPPING["hosts"].items()},
        "claims": dict(CLAIMS),
        "projection_parity_sha256": ir["projection_parity_sha256"],
        "failures": failures,
        "first_failing_invariant": (f"{failures[0]['code']}: {failures[0]['reason']}"
                                    if failures else ""),
    }


def check_web_surface(root: Path, out: Path) -> dict[str, Any]:
    """G-S3-WEB semantic gate: exactly the five PIPD documents, source-derived,
    with capability-loss and NACK records. OPTIONAL_SITE_UI is excluded."""
    out = Path(out)
    ir = compile_projection_ir(root)
    validate_projection_ir(ir)
    failures: list[dict] = []
    rows: list[dict] = []

    expected_top = set(WEB_DOC_FILES) | {IR_FILE, UI_DIR} \
        | {spec["dir"] for spec in ADAPTER_MAPPING["hosts"].values()}
    # The generated-surface marker is not a Web/Host/IR artefact: it never
    # appears in the denominator or the strict set equality.
    present_top = {p.name for p in out.iterdir()} if out.is_dir() else set()
    present_top.discard(MARKER_FILE)
    if present_top != expected_top:
        failures.append(_fail(WrongWebSet,
                              f"web surface set mismatch: expected {sorted(expected_top)}, "
                              f"present {sorted(present_top)} — the site UI five files can never "
                              "be the Web pack", "dist/web"))

    artifacts_by_path = {a["path"]: a for a in ir["artifacts"]}
    for art in ir["artifacts"]:
        if art["kind"] != WEB_DOC_KIND:
            continue
        path = art["path"]
        fpath = out / path
        row = {"doc_id": art["payload"]["doc_id"], "path": path,
               "source_hash": art["source_hash"], "source_objects": len(art["source_objects"]),
               "capability_loss": len(art["capability_loss"]), "nack": len(art["nack"]),
               "denominator": art["denominator"], "fresh": False, "derived": False}
        rows.append(row)
        if not fpath.is_file():
            failures.append(_fail(WrongWebSet, f"web document {path} absent", path))
            continue
        text = fpath.read_text(encoding="utf-8")
        if not text.strip():
            failures.append(_fail(EmptyPayload, f"web document {path} is empty", path))
            continue
        match = _META_RE.search(text)
        if not match:
            failures.append(_fail(MissingField, f"web document {path} has no PIPD-DOC-META block",
                                  path))
            continue
        try:
            meta = json.loads(match.group(1))
        except json.JSONDecodeError as exc:
            failures.append(_fail(MissingField, f"meta block is not JSON: {exc}", path))
            continue
        for key in ("schema", "schema_version", "doc_id", "kind", "denominator",
                    "source_objects", "source_hash", "capability_loss", "nack", "scope"):
            if key not in meta:
                failures.append(_fail(MissingField, f"meta block missing {key}", path))
                break
        else:
            if meta["kind"] != WEB_DOC_KIND:
                failures.append(_fail(DenominatorLeak,
                                      f"document kind {meta['kind']!r} is not a web document", path))
            if meta["denominator"] is not True:
                failures.append(_fail(DenominatorLeak,
                                      "web document was removed from the denominator", path))
            for scope_entry in meta["scope"]:
                if scope_entry not in ALLOWED_SCOPE:
                    failures.append(_fail(ScopeWidening,
                                          f"meta scope {scope_entry!r} widens authority", path))
            for recs, fields, name in ((meta["capability_loss"], LOSS_FIELDS, "CapabilityLoss"),
                                       (meta["nack"], NACK_FIELDS, "NACK")):
                if not isinstance(recs, list) or not recs:
                    failures.append(_fail(EmptyPayload,
                                          f"document {path} carries no {name} record", path))
                    continue
                for item in recs:
                    for key in fields:
                        if key not in item or item[key] in (None, ""):
                            failures.append(_fail(MissingField,
                                                  f"{name} record missing {key}", path))
                            break
            fresh = True
            for ref in meta["source_objects"]:
                for key in SOURCE_REF_FIELDS:
                    if key not in ref or not ref[key]:
                        failures.append(_fail(MissingField, f"source ref missing {key}", path))
                        fresh = False
                        break
                else:
                    live = ir["source_index"]
                    live_hashes = {r["object_id"]: r["source_hash"] for r in live}
                    if ref["object_id"] not in live_hashes:
                        failures.append(_fail(UnknownSourceObject,
                                              f"unknown source object {ref['object_id']!r}", path))
                        fresh = False
                    elif ref["source_hash"] != live_hashes[ref["object_id"]]:
                        failures.append(_fail(StaleSource,
                                              f"stale source hash for {ref['object_id']}; "
                                              "regenerate the projection", path))
                        fresh = False
            row["fresh"] = fresh
            if meta["source_hash"] != art["source_hash"]:
                failures.append(_fail(StaleSource,
                                      f"document source hash {meta['source_hash']} != live "
                                      f"{art['source_hash']}", path))
        if text != render_web_doc(art):
            failures.append(_fail(NotDerived,
                                  f"web document {path} content is not derived from the canonical "
                                  "objects/profiles (free text or tampered)", path))
        else:
            row["derived"] = True

    # PROJECTION_IR.json traceability + the three mandated IR negatives on disk
    ir_path = out / IR_FILE
    if ir_path.is_file():
        try:
            disk_ir = json.loads(ir_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            failures.append(_fail(MissingField, f"PROJECTION_IR.json is not JSON: {exc}", IR_FILE))
            disk_ir = None
        if disk_ir is not None:
            try:
                validate_projection_ir(disk_ir)
                if disk_ir.get("projection_parity_sha256") != ir["projection_parity_sha256"]:
                    failures.append(_fail(ParityMismatch,
                                          "PROJECTION_IR.json parity hash diverges from the "
                                          "canonical sources", IR_FILE))
            except ProjectionError as exc:
                failures.append(exc.failure(IR_FILE))
    else:
        failures.append(_fail(MissingField, "PROJECTION_IR.json absent", IR_FILE))

    # OPTIONAL_SITE_UI: present, exactly the five files, never in the denominator
    ui_dir = out / UI_DIR
    if ui_dir.is_dir():
        ui_present = sorted(p.name for p in ui_dir.iterdir() if p.is_file())
        if ui_present != sorted(UI_FILES):
            failures.append(_fail(WrongWebSet,
                                  f"OPTIONAL_SITE_UI file set {ui_present} != {sorted(UI_FILES)}",
                                  UI_DIR))
    for art in ir["artifacts"]:
        if art["kind"] == UI_KIND and art["denominator"]:
            failures.append(_fail(DenominatorLeak,
                                  "OPTIONAL_SITE_UI leaked into the Web denominator", UI_DIR))

    denominator_docs = [r for r in rows if r["denominator"]]
    verdict = "PASS" if not failures else "FAIL"
    return {
        "schema": "PIPD-WEB-PACK-CHECK/1",
        "surface": "web",
        "verdict": verdict,
        "expected": sorted(WEB_DOC_FILES),
        "denominator": {"expected": 5, "present": len(denominator_docs),
                        "ratio": f"{len(denominator_docs)}/5",
                        "optional_site_ui_excluded": len(UI_FILES),
                        "note": "exact-set equality over the five PIPD documents; OPTIONAL_SITE_UI "
                                "is excluded from the denominator and can never pass"},
        "rows": rows,
        "capability_loss": [r for art in ir["artifacts"] if art["kind"] == WEB_DOC_KIND
                            for r in art["capability_loss"]][:len(WEB_CAPABILITY_LOSS)],
        "nack": [r for art in ir["artifacts"] if art["kind"] == WEB_DOC_KIND
                 for r in art["nack"]][:len(WEB_NACK)],
        "claims": dict(CLAIMS),
        "projection_parity_sha256": ir["projection_parity_sha256"],
        "failures": failures,
        "first_failing_invariant": (f"{failures[0]['code']}: {failures[0]['reason']}"
                                    if failures else ""),
    }
