#!/usr/bin/env python3
"""REC08 F3-d — SBL three-Kind product factory (CANDIDATE).

REC08 §F3-d / §2.1: SBL must produce, from three NEW non-prebaked intents, a real
`CLI_TOOL`, `AGENT_SKILL` and `SIMPLE_AGENT`, each with a genuine
install / invoke / deny / uninstall cycle and user-visible output. A manifest, a fixture or
a deferred generator does not count.

This module only BUILDS. Lifecycle (install/invoke/deny/uninstall) lives in lifecycle.py and
the driver is run_three_kinds.py. Nothing here touches an SBL repo path: candidates are written
under the R17 write-set, so the claim ceiling is CANDIDATE_TESTED, not NATIVE.
"""
from __future__ import annotations

import json
import re
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

VALID_KINDS = ("CLI_TOOL", "AGENT_SKILL", "SIMPLE_AGENT")


@dataclass(frozen=True)
class Intent:
    """A source-bound product intent. Every field must come from the caller, not a template."""

    intent_id: str
    kind: str
    title: str
    fuo: str                       # first useful outcome, measurable
    non_goals: tuple[str, ...]
    source_clause: str             # KB locator, e.g. DOC02:L1234
    triggers: tuple[str, ...] = ()
    allowed_tools: tuple[str, ...] = ()
    denied_tools: tuple[str, ...] = ()

    def validate(self) -> None:
        if self.kind not in VALID_KINDS:
            raise ValueError(f"KIND_NOT_IN_V01_SCOPE:{self.kind}")
        if not self.source_clause or ":" not in self.source_clause:
            raise ValueError(f"SOURCE_CLAUSE_MISSING:{self.intent_id}")
        if not self.fuo.strip():
            raise ValueError(f"FUO_MISSING:{self.intent_id}")
        if self.kind == "AGENT_SKILL" and not self.triggers:
            raise ValueError(f"SKILL_TRIGGERS_MISSING:{self.intent_id}")
        if self.kind == "SIMPLE_AGENT" and not self.allowed_tools:
            raise ValueError(f"AGENT_ALLOWLIST_MISSING:{self.intent_id}")


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(text).lstrip("\n"), encoding="utf-8")
    return path


def _module_name(intent_id: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", intent_id.lower()).strip("_")


# --------------------------------------------------------------------------- CLI_TOOL
CLI_BODY = '''
"""Generated by SBL three-Kind factory. FUO: {fuo}"""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path

VERSION = "0.1.0"


def count_text(text: str) -> dict:
    return {{"lines": text.count("\\n") + (0 if text.endswith("\\n") else 1) if text else 0,
             "words": len(text.split()),
             "chars": len(text)}}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="{prog}", description="{fuo}")
    ap.add_argument("path", nargs="?", help="file to measure (default: stdin)")
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    ap.add_argument("--version", action="version", version=VERSION)
    args = ap.parse_args(argv)

    if args.path:
        p = Path(args.path)
        if not p.is_file():
            print(json.dumps({{"ok": False, "code": "INPUT_NOT_FOUND", "path": str(p)}})
                  if args.json else f"error: INPUT_NOT_FOUND: {{p}}", file=sys.stderr)
            return 2
        text = p.read_text(encoding="utf-8", errors="replace")
    else:
        text = sys.stdin.read()

    result = count_text(text)
    result["ok"] = True
    if args.json:
        print(json.dumps(result, ensure_ascii=False))
    else:
        print(f"{{result['lines']}} lines, {{result['words']}} words, {{result['chars']}} chars")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

CLI_TEST = '''
"""Generated acceptance test: FUO must be observable through the installed entrypoint."""
import json
import subprocess
import sys
from pathlib import Path


def test_json_contract(tmp_path: Path) -> None:
    f = tmp_path / "sample.txt"
    f.write_text("alpha beta\\ngamma\\n", encoding="utf-8")
    out = subprocess.run([sys.executable, "-m", "{module}.cli", "--json", str(f)],
                         capture_output=True, text=True, check=True)
    payload = json.loads(out.stdout)
    assert payload == {{"lines": 2, "words": 3, "chars": 17, "ok": True}}


def test_missing_input_is_typed_nonzero(tmp_path: Path) -> None:
    out = subprocess.run([sys.executable, "-m", "{module}.cli", "--json", str(tmp_path / "nope")],
                         capture_output=True, text=True)
    assert out.returncode == 2
    assert json.loads(out.stderr)["code"] == "INPUT_NOT_FOUND"
'''


def build_cli_tool(intent: Intent, root: Path) -> dict:
    intent.validate()
    module = _module_name(intent.intent_id)
    dist = intent.intent_id.replace("_", "-")
    pkg = root / dist
    _write(pkg / "pyproject.toml", f"""
        [build-system]
        requires = ["setuptools>=68"]
        build-backend = "setuptools.build_meta"

        [project]
        name = "{dist}"
        version = "0.1.0"
        description = "{intent.fuo}"
        requires-python = ">=3.10"
        license = {{text = "MIT"}}

        [project.scripts]
        {dist} = "{module}.cli:main"

        [tool.setuptools.packages.find]
        where = ["src"]
    """)
    _write(pkg / "src" / module / "__init__.py", f'__version__ = "0.1.0"\n')
    _write(pkg / "src" / module / "cli.py",
           CLI_BODY.format(fuo=intent.fuo, prog=dist))
    _write(pkg / "tests" / "test_cli.py", CLI_TEST.format(module=module))
    _write(pkg / "SKILL.json", json.dumps({
        "intent_id": intent.intent_id, "kind": intent.kind, "title": intent.title,
        "fuo": intent.fuo, "non_goals": list(intent.non_goals),
        "source_clause": intent.source_clause, "entrypoint": f"{dist}",
    }, ensure_ascii=False, indent=2))
    return {"kind": intent.kind, "root": str(pkg), "entrypoint": dist, "module": module}


# --------------------------------------------------------------------------- AGENT_SKILL
SKILL_MD = """
---
name: {name}
description: {description}
version: 0.1.0
metadata:
  hermes:
    tags: [generated, release]
triggers:
{triggers}
---
# {title}

FUO: {fuo}

Non-goals: {non_goals}

## Procedure
1. Read the changelog the user points at. If no path is given, ask exactly one question.
2. Group entries by kind (added / changed / fixed / removed). Never invent an entry.
3. Emit a checklist with one line per entry, prefixed by its group.
4. State anything you could not determine as `UNKNOWN`, never as done.

## Source
{source_clause}
"""

REFERENCE_MD = """
# Reference: release checklist shape

Output contract (machine-readable companion):

    {"ok": bool, "groups": {"added": [...], "changed": [...], "fixed": [...], "removed": [...]},
     "unknown": [...]}

A checklist that omits an input line is a defect; an entry with no group is `UNKNOWN`.
"""


def build_agent_skill(intent: Intent, root: Path) -> dict:
    intent.validate()
    base = root / intent.intent_id.replace("_", "-")
    n = intent.intent_id.replace("_", "-")
    _write(base / "SKILL.md", SKILL_MD.format(
        name=n, description=intent.fuo, title=intent.title, fuo=intent.fuo,
        non_goals=", ".join(intent.non_goals) or "none",
        triggers="".join(f"  - {t}\n" for t in intent.triggers),
        source_clause=intent.source_clause))
    _write(base / "references" / "output_contract.md", REFERENCE_MD)
    manifest = {
        "name": n, "version": "0.1.0", "kind": intent.kind,
        "intent_id": intent.intent_id, "fuo": intent.fuo,
        "non_goals": list(intent.non_goals), "source_clause": intent.source_clause,
        "triggers": list(intent.triggers),
        "files": ["SKILL.md", "references/output_contract.md"],
    }
    _write(base / "manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
    return {"kind": intent.kind, "root": str(base), "name": n, "manifest": manifest}


# --------------------------------------------------------------------------- SIMPLE_AGENT
AGENT_RUNNER = '''
"""Generated bounded agent. Allowlist + stop policy + attributable receipt."""
from __future__ import annotations
import json
import sys
from pathlib import Path

ALLOWED = {allowed}
DENIED = {denied}
MAX_STEPS = {max_steps}


def _read_file(p: str) -> str:
    return Path(p).read_text(encoding="utf-8", errors="replace")


def _list_dir(p: str) -> list:
    return sorted(x.name for x in Path(p).iterdir())


TOOLS = {{"read_file": _read_file, "list_dir": _list_dir}}


def run(plan: list, receipt_path: str) -> dict:
    """Execute an explicit, caller-supplied plan. No self-directed loop, no network."""
    steps, stopped, code = [], False, None
    for i, step in enumerate(plan):
        if i >= MAX_STEPS:
            stopped, code = True, "STOP_STEP_BUDGET"
            break
        tool, arg = step.get("tool"), step.get("arg")
        if tool in DENIED or tool not in ALLOWED:
            steps.append({{"step": i, "tool": tool, "verdict": "DENIED",
                          "code": "TOOL_NOT_IN_ALLOWLIST"}})
            stopped, code = True, "STOP_DENIED_TOOL"
            break
        fn = TOOLS.get(tool)
        if fn is None:
            steps.append({{"step": i, "tool": tool, "verdict": "DENIED",
                          "code": "TOOL_UNIMPLEMENTED"}})
            stopped, code = True, "STOP_UNIMPLEMENTED_TOOL"
            break
        try:
            out = fn(arg)
            steps.append({{"step": i, "tool": tool, "verdict": "OK",
                          "bytes": len(out) if hasattr(out, "__len__") else 0}})
        except Exception as exc:
            steps.append({{"step": i, "tool": tool, "verdict": "ERROR", "code": type(exc).__name__}})
            stopped, code = True, "STOP_TOOL_ERROR"
            break
    receipt = {{"ok": code is None, "stopped": stopped, "stop_code": code,
               "steps": steps, "allowed": sorted(ALLOWED), "denied": sorted(DENIED)}}
    Path(receipt_path).write_text(json.dumps(receipt, ensure_ascii=False, indent=2), encoding="utf-8")
    return receipt


def main(argv: list[str]) -> int:
    if not argv:
        print("usage: run <plan.json> <receipt.json>", file=sys.stderr)
        return 2
    plan = json.loads(Path(argv[0]).read_text(encoding="utf-8"))["plan"]
    receipt = run(plan, argv[1])
    print(json.dumps(receipt, ensure_ascii=False))
    return 0 if receipt["ok"] else 3


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
'''


def build_simple_agent(intent: Intent, root: Path, max_steps: int = 5) -> dict:
    intent.validate()
    base = root / intent.intent_id.replace("_", "-")
    _write(base / "agent.json", json.dumps({
        "intent_id": intent.intent_id, "kind": intent.kind, "title": intent.title,
        "fuo": intent.fuo, "non_goals": list(intent.non_goals),
        "source_clause": intent.source_clause,
        "tools": {"allowed": list(intent.allowed_tools), "denied": list(intent.denied_tools)},
        "stop_policy": {"max_steps": max_steps, "on_denied_tool": "STOP_DENIED_TOOL",
                        "on_tool_error": "STOP_TOOL_ERROR", "self_directed_loop": False},
        "network": False,
    }, ensure_ascii=False, indent=2))
    _write(base / "runner.py", AGENT_RUNNER.format(
        allowed=repr(tuple(intent.allowed_tools)),
        denied=repr(tuple(intent.denied_tools)),
        max_steps=max_steps))
    return {"kind": intent.kind, "root": str(base), "runner": str(base / "runner.py")}
